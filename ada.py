lines = list(csv.reader(io.StringIO(raw)))

# ── Build column labels from row 2 (main) + row 3 (sub-qualifier) ──
main_row = lines[2]
sub_row  = lines[3]

col_labels = {}
for i in range(1, max(len(main_row), len(sub_row))):
    main = main_row[i].strip() if i < len(main_row) else ""
    sub  = sub_row[i].strip()  if i < len(sub_row)  else ""
    if main:
        col_labels[i] = main + sub   # e.g. "ซลอ" + "ขาว" → "ซลอขาว"

# ── Parse data rows (start at index 4, skip header rows 0-3) ──
results = []

for row in lines[4:]:
    # Skip blank rows
    if not any(c.strip() for c in row):
        continue

    product = row[0].strip()

    # Skip rows with no product ID in col 0
    if not product:
        continue

    # Skip annotation/label rows: product cell contains Thai text only (no alphanumeric)
    if not any(c.isascii() and c.isalnum() for c in product):
        continue

    for col_idx, label in col_labels.items():
        if col_idx >= len(row):
            continue
        val = row[col_idx].strip()
        if not val:
            continue
        try:
            qty = int(val)
            results.append(f"{product},{label},{qty}")
        except ValueError:
            pass  # skip text cells (AW01, -ขาวเมล่า, etc.)

# ── Write output ──
